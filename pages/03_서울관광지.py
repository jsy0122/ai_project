# 지도 생성
m = folium.Map(
    location=[37.5665, 126.9780],
    zoom_start=11,
    tiles="OpenStreetMap"
)

# 파란색 마커 추가
for name, info in places.items():
    folium.Marker(
        location=[info["lat"], info["lon"]],
        popup=f"""
        <h4>{name}</h4>
        <p>{info['desc']}</p>
        """,
        tooltip=name,
        icon=folium.Icon(
            color="blue",
            icon="info-sign"
        )
    ).add_to(m)

# 지도 크기 60%
col1, col2, col3 = st.columns([2, 6, 2])

with col2:
    st_folium(m, width=750, height=500)

st.divider()

# 관광지 선택
st.subheader("📌 관광지 자세히 알아보기")

selected_place = st.selectbox(
    "궁금한 관광지를 선택해봐 👇",
    list(places.keys())
)

info = places[selected_place]

# 상세 정보 출력
st.markdown(f"## {selected_place}")
st.markdown(f"### {info['station']}")
st.markdown(info["fun"])


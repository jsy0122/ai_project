# 서울 중심 지도
m = folium.Map(
    location=[37.5665, 126.9780],
    zoom_start=11,
    tiles="OpenStreetMap"
)

# 마커 추가
for name, info in places.items():
    folium.Marker(
        location=[info["lat"], info["lon"]],
        popup=f"""
        <h4>{name}</h4>
        <p>{info['desc']}</p>
        """,
        tooltip=name,
        icon=folium.Icon(color="red", icon="star")
    ).add_to(m)

# 지도 크기 60% 정도로 축소
col1, col2, col3 = st.columns([1, 6, 1])

with col2:
    st_folium(m, width=800, height=500)

st.divider()

